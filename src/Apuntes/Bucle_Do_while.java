package Apuntes;

public class Bucle_Do_while {
    public static void main(String[] args) {

//        Bucle do while:
//        Estructura es: do {
//        -- acciones del bucle --
//        } while (condición);

        int i = 0, n = 10;

        do {
            System.out.println(i);
            i++;
        } while (i <= n);
    }
}