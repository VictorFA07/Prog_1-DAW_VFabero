package Apuntes;

public class Bucle_While {
    public static void main(String[] args) {

//        Bucle while:
//        Estructura es: while (condición) {
//        -- acciones del bucle --
//        }

        int i = 0, n = 10;

        while (i <= n) {
            System.out.println(i + " ");
            i++;
        }
    }
}